const list = await (await fetch("http://127.0.0.1:9223/json/list")).json();
const ws = new WebSocket(list.find(t => t.type === "page").webSocketDebuggerUrl);
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
let seq = 0;
const pending = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
const send = (method, params = {}) => new Promise((res) => { const id = ++seq; pending.set(id, res); ws.send(JSON.stringify({ id, method, params })); });
await send("Runtime.enable");
const before = await send("Runtime.evaluate", { expression: "localStorage.getItem('afvi-theme')", returnByValue: true });
console.log("current:", JSON.stringify(before.result?.result?.value));
await send("Runtime.evaluate", { expression: "localStorage.setItem('afvi-theme','dark')" });
const after = await send("Runtime.evaluate", { expression: "localStorage.getItem('afvi-theme')", returnByValue: true });
console.log("reset to:", JSON.stringify(after.result?.result?.value));
ws.close();
process.exit(0);
